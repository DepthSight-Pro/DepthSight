# 1. TEST 1: PYDANTIC SCHEMA VALIDATION & ROUND-TRIP SERIALIZATION INTEGRITY
# ============================================================================================
def test_ui_export_pydantic_schema_validation_roundtrip():
    """
    Validates that the raw visual editor JSON export matches StrategyV2ConfigData schema
    verbatim, and can be serialized back and forth with zero field drops.
    """
    raw_config = load_raw_ui_config()

    # 1. Validate against Pydantic StrategyV2ConfigData
    validated_v2 = schemas.StrategyV2ConfigData.model_validate(raw_config)
    assert validated_v2.strategy_name == "VisualBuilderStrategy"
    assert validated_v2.symbol == "BTCUSDT"
    assert validated_v2.marketType == "FUTURES"
    assert validated_v2.entryTrigger.type == "on_candle_close"
    assert validated_v2.entryTrigger.timeframe == "5m"

    # Verify counts match the UI structure
    assert len(validated_v2.filters.children or []) == 10
    assert len(validated_v2.entryConditions.children or []) == 18
    assert len(validated_v2.positionManagement or []) == 7

    # 2. Round-trip serialization
    dumped = validated_v2.model_dump(by_alias=True, exclude_none=True)
    assert dumped["symbol"] == raw_config["symbol"]
    assert dumped["marketType"] == raw_config["marketType"]
    assert (
        dumped["entryTrigger"]["timeframe"] == raw_config["entryTrigger"]["timeframe"]
    )

    # 3. Validate against StrategyConfigCreate (API Endpoint Schema)
    strategy_create_payload = {
        "name": "Live Master Strategy from UI",
        "description": "Exported from React Strategy Editor",
        "config_data": raw_config,
        "symbol_selection_mode": "STATIC",
        "symbols": ["BTCUSDT"],
        "use_ml_confirmation": False,
    }
    api_schema = schemas.StrategyConfigCreate.model_validate(strategy_create_payload)
    assert api_schema.name == "Live Master Strategy from UI"
    assert api_schema.config_data is not None


