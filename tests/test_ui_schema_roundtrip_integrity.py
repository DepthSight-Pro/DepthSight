def load_raw_ui_config(file_path: Optional[str] = None) -> Dict[str, Any]:
    """
    Loads UI strategy config.
    1. Checks explicit file_path if provided.
    2. Checks UI_STRATEGY_TEST_PATH env var.
    3. Searches workspace root for 'New_Strategy_config*.json'.
    4. Falls back to embedded GOLDEN_UI_MASTER_CONFIG (100% standalone, zero external file dependency).
    """
    # 1. Explicit path
    if file_path and os.path.exists(file_path):
        with open(file_path, "r", encoding="utf-8") as f:
            return json.load(f)

    # 2. Env variable
    env_path = os.getenv("UI_STRATEGY_TEST_PATH")
    if env_path and os.path.exists(env_path):
        with open(env_path, "r", encoding="utf-8") as f:
            return json.load(f)

    # 3. Search in workspace root
    root_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    candidates = glob.glob(os.path.join(root_dir, "New_Strategy_config*.json"))
    if candidates and os.path.exists(candidates[0]):
        try:
            with open(candidates[0], "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            pass

    # 4. Fallback to embedded Golden Master
    return copy.deepcopy(GOLDEN_UI_MASTER_CONFIG)


def _collect_node_ids(node: Dict[str, Any], collected: Set[str]) -> None:
    """Recursively collects all UUIDs/node IDs from a condition tree."""
    if not isinstance(node, dict):
        return
    node_id = node.get("id")
    if node_id:
        collected.add(node_id)
    children = node.get("children")
    if isinstance(children, list):
        for child in children:
            _collect_node_ids(child, collected)
    if_conditions = node.get("if_conditions")
    if isinstance(if_conditions, dict):
        _collect_node_ids(if_conditions, collected)


def _collect_trace_ids(trace: Dict[str, Any], collected: Set[str]) -> None:
    """Recursively collects all node IDs visited in an evaluation trace tree."""
    if not isinstance(trace, dict):
        return
    node_id = trace.get("id")
    if node_id:
        collected.add(node_id)
    children = trace.get("children")
    if isinstance(children, list):
        for child in children:
            _collect_trace_ids(child, collected)


